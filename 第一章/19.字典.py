# 字典 ---- key不能重复，而且key要为不可变的内容，set、list因为可变都不行
# 定义字典
dict1 = {"小红":607, "小明":670, "李牧晚":580, "韩立":688}
print(dict1)
print(type(dict1))
dict1 = {"小红":607, "小明":670, "李牧晚":580, "韩立":688, "小明":700}
# 不能重复，如果重复，后面的值会覆盖前面的值
print(dict1)
# key为不能更改的元素，都可以
dict2 = {1:1, 65.32:98, (1,2,3):699}
# 以下就会报错
# dict2 = {1:1, 65.32:98, (1,2,3):699, [89]:655}
print(dict2)
# -------------------------------------------------------
# 访问字典的元素：[]
print(dict1['小红'])
dict1['小红'] = 688
print(dict1)
# 字典的value值是可以修改的