import re
s1 ="18809090000是我的手机号，你记住了吗?我的另一个手机号是18800008888，两个QQ号分别是155998992 和 18809091293821 你记住了吗?"
s2 ="我的手机号是18809090000，你记住了吗?我的另一个手机号是18800008888，两个QQ号分别是155998992 和 18809091293821你记住了吗?"

# 1、match - 从字符串的开头开始匹配 ----> 返回match对象
# 如果要字符串中的\后面起到原来的作用（不转义），可以在前面加一个r or 两个\
# 比如这里用r
# 从头开始匹配，规则为第一个参数，查找对象是第二个参数 如果找到则返回第一个位置
# 否则则返回None 只会匹配第一个匹配项
# 注：如果匹配s2则为None，因为从头开始，第一位是“我”，因此没有1
result = re.match(r"1[3-9]\d{9}", s1)
# 获取匹配到的结果
print(result.group())
# 开始位置和结束位置
print(result.span())
# 获得开始索引
print(result.start())
# 获得结束索引
print(result.end())

print("-----------------------------------------------")
# 2、search - 从任意位置开始搜索，直到搜索到第一个结果 -> match对象
# 注：从任意位置开始
result = re.search(r"1[3-9]\d{9}", s2)
# 获取匹配到的结果
print(result.group())
# 开始位置和结束位置 ---> tuple
print(result.span())
# 获得开始索引
print(result.start())
# 获得结束索引
print(result.end())

print("-----------------------------------------------")

# 3、findall - 从任意位置开始，搜索所有匹配项 -> list
# 就是 ctrl + F 那样，找到全部内容
result = re.findall(r"1[3-9]\d{9}", s2)
# 获取匹配到的结果
print(result)
